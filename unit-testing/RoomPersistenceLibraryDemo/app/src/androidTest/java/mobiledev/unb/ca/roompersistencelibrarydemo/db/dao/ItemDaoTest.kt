package mobiledev.unb.ca.roompersistencelibrarydemo.db.dao

import kotlinx.coroutines.runBlocking
import kotlinx.coroutines.flow.first
import mobiledev.unb.ca.roompersistencelibrarydemo.db.DatabaseTest
import mobiledev.unb.ca.roompersistencelibrarydemo.db.entities.Item
import org.junit.Assert
import org.junit.Before
import org.junit.Test

class ItemDaoTest: DatabaseTest() {
    private lateinit var itemDao: ItemDao

    @Before
    fun setup() {
        itemDao = appDatabase.itemDao()
    }

    @Test
    fun getAllItemsFlow_emitsItemsOrderedByIdAscending() = runBlocking {
        // Verify initial empty state
        Assert.assertEquals(emptyList<Item>(), itemDao.getAllItemsFlow().first())

        val item3 = Item(id = 3L, name = "Third", num = 30)
        val item1 = Item(id = 1L, name = "First", num = 10)
        val item2 = Item(id = 2L, name = "Second", num = 20)

        // Insert items out of order and verify ascending sort
        itemDao.insertItem(item3)
        itemDao.insertItem(item1)
        itemDao.insertItem(item2)
        Assert.assertEquals(listOf(item1, item2, item3), itemDao.getAllItemsFlow().first())

        // Delete middle item and verify updated snapshot
        itemDao.deleteItem(item2)
        Assert.assertEquals(listOf(item1, item3), itemDao.getAllItemsFlow().first())
    }

    @Test
    fun getAllItemsFlow_handlesAutoGeneratedIdsAndConflictIgnore() = runBlocking {
        // Insert with default id = 0 -> generates id = 1L
        val generatedId = itemDao.insertItem(Item(name = "Alpha", num = 100))
        Assert.assertEquals(1L, generatedId)
        Assert.assertEquals(
            listOf(Item(id = 1L, name = "Alpha", num = 100)),
            itemDao.getAllItemsFlow().first()
        )

        // Duplicate primary key is ignored and table state remains unchanged
        val ignoredResult = itemDao.insertItem(Item(id = 1L, name = "Duplicate", num = 999))
        Assert.assertEquals(-1L, ignoredResult)
        Assert.assertEquals(
            listOf(Item(id = 1L, name = "Alpha", num = 100)),
            itemDao.getAllItemsFlow().first()
        )
    }
}